def print_status(message):
    print(f"[✓] {message}")

def print_error(message):
    print(f"[✗] {message}")


def print_section(title):
    print("\n" + "─" * 62)
    print(f"{title:^62}")
    print("─" * 62)


def print_step(message):
    print(f"  → {message}")

